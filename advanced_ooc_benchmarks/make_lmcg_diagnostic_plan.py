"""Generate an LMCG GC/broker/prefetch diagnostic, reusing the main datasets."""
import argparse
import copy
from pathlib import Path

import yaml


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?", type=Path,
                        default=Path(__file__).with_name("benchmark-plan.yaml"))
    parser.add_argument("-o", "--output", type=Path)
    parser.add_argument("--higher", action="store_true",
                        help="sweep 4/5/6 GiB workers and 2/2.5/3 GiB prefetch at 32 MiB regions")
    args = parser.parse_args()
    source = args.source.read_text()
    plan = yaml.safe_load(source)
    reference = next(run for run in plan["runs"] if run["id"] == "lmcg")
    prefix = source.split("\nruns:", 1)[0]
    prefix = prefix.replace("results: ${plan.root}/bench-results",
                            "results: ${plan.root}/lmcg-diagnostic-results", 1)
    if args.higher:
        prefix = prefix.replace("lmcg-diagnostic-results", "lmcg-higher-results", 1)
    prefix = prefix.replace("-XX:G1HeapRegionSize=8m", """-XX:G1HeapRegionSize=${run.g1_region}m
      -Xlog:gc*,safepoint:file=${run.results}/gc.log:time,uptime,level,tags
      -XX:StartFlightRecording=filename=${run.results}/profile.jfr,settings=profile,dumponexit=true,maxsize=128m""", 1)
    runs = []

    def add(name, region, broker=None, prefetch=None, cache_soft=4, cache_hard=4.5,
            prefetch_gib=None, replay_mib=768, replay_blocks=64):
        run = copy.deepcopy(reference)
        run["id"] = name
        run["resource_profiles"] = ["mem16"]
        run["blocksize_sweeps"] = {"ooc": [1500]}
        run["implementations"] = [{"id": "systemds-ooc", "template": "systemds-ooc"}]
        run["parameters"]["g1_region"] = region
        if broker is not None:
            # Reserve identical cache capacity even when either broker grows.
            settings = {
                "memory.broker.fraction": 0.5,
                "memory.broker.max": broker * 1024**3,
                "memory.prefetch.fraction": 0.25,
                "memory.prefetch.max": (int(prefetch_gib * 1024**3) if prefetch_gib is not None
                                        else 2 * 1024**3 if prefetch else 1000 * 1024**2),
                "memory.cache.fraction.soft": cache_soft / 12,
                "memory.cache.fraction.hard": cache_hard / 12,
                "source.bulksize": (replay_mib if prefetch else 300) * 1024**2,
                "source.replay.memory": (replay_mib if prefetch else 300) * 1024**2,
                "source.replay.prefetch": replay_blocks if prefetch else 32,
            }
            xml = "".join(f"  <sysds.ooc.{key}>{value}</sysds.ooc.{key}>\n"
                          for key, value in settings.items())
            run["setup"]["command"] = run["setup"]["command"].replace("</root>", xml + "</root>", 1)
        runs.append(run)

    if args.higher:
        add("lmcg_previous_winner_start", 32, 4, 1)
        prefetch_levels = [(2, 768, 64), (2.5, 1024, 96), (3, 1280, 128)]
        for broker in (4, 5, 6):
            levels = prefetch_levels if broker != 5 else reversed(prefetch_levels)
            for prefetch_gib, replay_mib, replay_blocks in levels:
                label = str(prefetch_gib).replace(".", "p")
                add(f"lmcg_higher_b{broker}_pf{label}", 32, broker, 1,
                    cache_soft=1, cache_hard=1.5, prefetch_gib=prefetch_gib,
                    replay_mib=replay_mib, replay_blocks=replay_blocks)
        add("lmcg_previous_winner_end", 32, 4, 1)
    else:
        add("lmcg_control_start", 8)
        # Alternate region order between pairs to reduce a simple time-order bias.
        for broker, prefetch, regions in [(3, 0, (8, 32)), (4, 0, (32, 8)),
                                          (3, 1, (8, 32)), (4, 1, (32, 8))]:
            for region in regions:
                add(f"lmcg_g{region}_b{broker}_p{prefetch}", region, broker, prefetch)
        add("lmcg_control_end", 8)
    target = args.output or args.source.with_name(
        "benchmark-plan-lmcg-higher.yaml" if args.higher else "benchmark-plan-lmcg-diagnostic.yaml")
    target.write_text(prefix + "\n\n# Generated by make_lmcg_diagnostic_plan.py; controls bracket the sweep.\n"
                      + yaml.safe_dump({"runs": runs}, sort_keys=False))
    print(f"Wrote {target}: {len(runs)} executions, 12 GiB heap / 16 GiB cgroup each")


if __name__ == "__main__":
    main()
